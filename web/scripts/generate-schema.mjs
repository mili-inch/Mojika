import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const schema = JSON.parse(execFileSync('uv', ['run', '--locked', 'python', '-m', 'mojika.server.schema'], { cwd: '..', encoding: 'utf8' }));
await writeFile('src/api-types.ts', await compile(schema, 'Contract', { ignoreMinAndMaxItems: true, bannerComment: '/* Generated by scripts/generate-schema.mjs from mojika.server.schema. */' }));
